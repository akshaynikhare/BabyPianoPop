"""Rebuild assets/audio/MANIFEST.md from the rendered files, eleven_sounds.csv and eleven_lines.csv.

  /Users/akshay/Downloads/baby_apps/.tools/kokoro-venv/bin/python tools/audio/make_manifest.py
"""
import soundfile as sf

from verify_assets import AUDIO, clips


def table(folder, bus, descs):
    lines = [f"## {folder}/ ({bus} bus)", "", "| id | duration | what it is |", "|---|---|---|"]
    for p in sorted((AUDIO / folder).glob("*.ogg")):
        if p.stem.startswith("smoke_"):
            continue
        lines.append(f"| `{p.stem}` | {sf.info(str(p)).duration:.2f} s | {descs.get(p.stem, '')} |")
    return "\n".join(lines) + "\n"


def main():
    descs = clips()
    descs["music"] = {k: f"{v}. Loops: loop=true in its .import file" for k, v in descs["music"].items()}
    out = ["# BabyPianoPop audio manifest", "",
           "Generated by `tools/audio/make_manifest.py` from `eleven_sounds.csv` (prompts) and `eleven_lines.csv` (spoken lines). "
           "Load by name through `AudioDirector` (`assets/audio/{sfx,voice,music}/<name>.ogg`). SFX and music are mono 44.1 kHz; voice is mono 24 kHz.",
           "Loudness: one-shots -22 LUFS, `ui_*` -25, music -20, voice -16. The AudioDirector buses balance them: Voice 0 dB (the anchor), "
           "SFX -3 dB, Music -6 dB (10 dB under the voice), and a -1 dB limiter on Master.",
           "SFX kept more than once are variant groups: `pop_1`..`pop_4` play as `pop` (`play_sfx(&\"pop\")` picks one at random, never the same twice in a row).",
           "Indexed voice ids are zero-based: `praise_0`..`praise_11` follow PRAISE_PHRASES order, `mascot_0`..`mascot_5` "
           "MASCOT_PHRASES, `gear_0`..`gear_3` SETTING_TAP_PHRASES; `three_stars_praise_<n>` is \"Three stars! \" + `praise_<n>`.",
           "Spoken text is the line sent to the TTS; some letters are spelled out (\"Eff\", \"Ess\") so the voice says the letter's name.", "",
           table("sfx", "SFX", descs["sfx"]), table("music", "Music", descs["music"]), table("voice", "Voice", descs["voice"])]
    (AUDIO / "MANIFEST.md").write_text("\n".join(out))


if __name__ == "__main__":
    main()
