"""Rebuild assets/audio/MANIFEST.md from the rendered files and voice_lines.csv.

  /Users/akshay/Downloads/baby_apps/.tools/kokoro-venv/bin/python tools/audio/make_manifest.py
"""
import csv
import pathlib
import soundfile as sf

HERE = pathlib.Path(__file__).resolve().parent
AUDIO = HERE.parents[1] / "assets/audio"

SFX = {
    "pop": "Tile pop: sine 523 to 1047 Hz sweep, 80 ms",
    "giggle": "Mascot tap: three sine notes 659 / 784 / 1047 Hz, 80 ms apart",
    "star": "Three-star chime / star pill: triangles 1319 + 1976 Hz, 60 ms apart",
    "tick": "Gear short-press click: sine 880 to 1760 Hz, 60 ms",
}
for hz, note in [(523, "C5"), (587, "D5"), (659, "E5"), (784, "G5"), (880, "A5"), (1047, "C6"), (1175, "D6")]:
    SFX[f"chime_{hz}"] = f"Music-box bell, {note} (melody frequency rounded half-up to {hz} Hz): sine + 3.01x partial, 2.8 kHz lowpass"
MUSIC = {
    "music_box": "28-note pentatonic melody, 520 ms steps (950 ms after notes 8/16/24); one seamless 15.85 s loop with the tail wrapped onto the head. loop=true in its .import file",
}


def table(folder, bus, descs):
    lines = [f"## {folder}/ ({bus} bus)", "", "| id | duration | what it is |", "|---|---|---|"]
    for p in sorted((AUDIO / folder).glob("*.ogg")):
        if p.stem.startswith("smoke_"):
            continue
        lines.append(f"| `{p.stem}` | {sf.info(str(p)).duration:.2f} s | {descs.get(p.stem, '')} |")
    return "\n".join(lines) + "\n"


def main():
    voice = {r["id"]: f"Says: \"{r['text']}\"" for r in csv.DictReader(open(HERE / "voice_lines.csv", encoding="utf-8"))}
    voice = {k: v.replace("[", "").replace("]", "") for k, v in voice.items()}
    out = ["# BabyPianoPop audio manifest", "",
           "Generated by `tools/audio/make_manifest.py`. Load by name through `AudioDirector` "
           "(`assets/audio/{sfx,voice,music}/<name>.ogg`). SFX and music are mono 44.1 kHz; voice is mono 24 kHz.",
           "SFX peak about -3 dBFS, music about -6 dBFS, voice about -16 LUFS (soft-limited below -1.5 dBFS).",
           "Indexed ids are zero-based: `praise_0`..`praise_5` follow PRAISE_PHRASES order, `mascot_0`..`mascot_5` "
           "MASCOT_PHRASES, `gear_0`..`gear_3` SETTING_TAP_PHRASES; `three_stars_praise_<n>` is \"Three stars! \" + `praise_<n>`.",
           "Letter clips use Kokoro phoneme markup so they say the letter name (A is read as \"ay\"); the text shown here is the spoken letter.", "",
           table("sfx", "SFX", SFX), table("music", "Music", MUSIC), table("voice", "Voice", voice)]
    (AUDIO / "MANIFEST.md").write_text("\n".join(out))


if __name__ == "__main__":
    main()
